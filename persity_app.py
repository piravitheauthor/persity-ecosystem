def format_and_validate_dob(dob_string):
    clean_dob = dob_string.strip()
    if len(clean_dob) == 8 and clean_dob.isdigit():
        clean_dob = f"{clean_dob[:2]}/{clean_dob[2:4]}/{clean_dob[4:]}"
    try:
        datetime.strptime(clean_dob, "%d/%m/%Y")
        return True, clean_dob
    except ValueError:
        return False, clean_dob


def calculate_DOB_value(dob):
  digits = [int(char) for char in dob if char.isdigit()]
  return sumOfDigits(sum(digits))


def calculate_date_value(dob):
  components = [int(x) for x in dob.split("/")]
  return sumOfDigits(components[0])


def calculate_name_value(name):
  mapping = {
      "a": 1, "i": 1, "j": 1, "q": 1, "y": 1,
      "b": 2, "k": 2, "r": 2,
      "c": 3, "g": 3, "l": 3, "s": 3,
      "d": 4, "m": 4, "t": 4,
      "e": 5, "h": 5, "n": 5, "x": 5,
      "u": 6, "v": 6, "w": 6,
      "o": 7, "z": 7,
      "f": 8, "p": 8,
  }
  total = sum(
      mapping[char] for char in name.lower() if char in mapping
  )
  return sumOfDigits(total)


def sumOfDigits(number):
  number = int(number)
  while number > 9:
    number = sum(int(d) for d in str(number))
  return number


def getCharacteristics(number: int) -> list[str]:
  characteristics_map = {
      1: ["Guiding", "Controlling", "Self-Assured", "Arrogant"],
      2: ["Cooperative", "People-Pleasing", "Empathic", "Overly Submissive"],
      3: ["Expressive", "Dramatic", "Creative", "Frivolous"],
      4: ["Reliable", "Rigid", "Practical", "Stubborn"],
      5: ["Spontaneous", "Impulsive", "Free-Spirited", "Careless"],
      6: ["Nurturing", "Smothering", "Responsible", "Martyr"],
      7: ["Introspective", "Withdrawn", "Analytical", "Cynical"],
      8: ["Ambitious", "Materialistic", "Competent", "Authoritarian"],
      9: ["Compassionate", "Self-Sacrificial", "Universal", "Detached"],
  }
  return characteristics_map.get(number, [])


